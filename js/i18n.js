  const STORAGE_KEY = "tablelens.lang";
  let current = "uk";
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && STRINGS[saved]) current = saved;
  } catch (e) { /* localStorage може бути недоступний */ }

  // t("ключ") або t("ключ", {n: 3}) — підстановка {n} у рядок.
  function t(key, vars) {
    const dict = STRINGS[current] || STRINGS.uk;
    let s = dict[key];
    if (s == null) s = (STRINGS.uk[key] != null ? STRINGS.uk[key] : key);
    if (vars) {
      for (const k in vars) s = s.split("{" + k + "}").join(vars[k]);
    }
    return s;
  }

  // Застосовує переклади до статичної розмітки сторінки.
  function applyDom() {
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = t(el.dataset.i18n);
    });
    document.querySelectorAll("[data-i18n-html]").forEach((el) => {
      el.innerHTML = t(el.dataset.i18nHtml);
    });
    document.querySelectorAll("[data-i18n-title]").forEach((el) => {
      el.title = t(el.dataset.i18nTitle);
    });
    document.querySelectorAll("[data-i18n-tip]").forEach((el) => {
      el.dataset.tip = t(el.dataset.i18nTip);
      el.setAttribute("aria-label", t(el.dataset.i18nTip));
    });
    document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
      el.placeholder = t(el.dataset.i18nPh);
    });
    document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      el.setAttribute("aria-label", t(el.dataset.i18nAria));
    });
    document.title = t("app.title");
    document.documentElement.lang = current;
  }

  function setLang(lang) {
    if (!STRINGS[lang]) return;
    current = lang;
    try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) { /* ignore */ }
    applyDom();
    // Перемальовуємо динамічні частини інтерфейсу, якщо вони вже існують.
    if (typeof window.__i18nRefresh === "function") window.__i18nRefresh();
    window.dispatchEvent(new CustomEvent("i18n:change", { detail: { lang: lang } }));
  }

  function getLang() { return current; }

  window.I18N = { t: t, setLang: setLang, getLang: getLang, applyDom: applyDom, STRINGS: STRINGS };
  // Глобальний шорткат для інших модулів.
  window.t = t;

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", applyDom);
  } else {
    applyDom();
  }
